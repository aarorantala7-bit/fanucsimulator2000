import {readFileSync,existsSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';
const html=readFileSync('index.html','utf8');
const scripts=[...html.matchAll(/<script src="([^"]+)"><\/script>/g)].map(m=>m[1]);
assert.equal(scripts.length,28);
for(const p of scripts) execFileSync(process.execPath,['--check',p],{stdio:'inherit'});
for(const p of [...html.matchAll(/(?:src|href)="((?:assets|src)\/[^"]+)"/g)].map(m=>m[1])) assert.ok(existsSync(p),p);
assert.ok(scripts.indexOf('src/state.js')===0);
assert.ok(scripts.at(-1)==='src/ui/import-dialog.js');
assert.ok(scripts.indexOf('src/ui/cnc-panel.js')<scripts.indexOf('src/import/nc-cleanup.js')&&scripts.indexOf('src/import/wincam.js')<scripts.indexOf('src/ui/import-dialog.js'));
for(const f of ['vendor/tesseract/tesseract.min.js','vendor/tesseract/worker.min.js','vendor/tesseract/tesseract-core-simd-lstm.wasm.js','vendor/tesseract/tesseract-core-lstm.wasm.js','vendor/tessdata/eng.traineddata.gz'])assert.ok(existsSync(f),f);
for(const gone of ['src/macros/gallery.js','src/macros/draft.js','src/macros/material.js','src/macros/combined.js','src/ui/reference.js'])assert.ok(!scripts.includes(gone),gone);
assert.ok(scripts.indexOf('src/nc/machine.js')<scripts.indexOf('src/tools/library.js'));
assert.ok(scripts.indexOf('src/ui/demos.js')<scripts.indexOf('src/ui/machine-mode.js'));
assert.ok(!scripts.some(p=>p.startsWith('src/ui/turning')));
console.log('Source checks passed; browser rendering is not covered.');
